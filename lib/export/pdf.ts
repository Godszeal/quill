import PDFDocument from "pdfkit";
import type { Chapter, Project } from "../types";
import { frontMatter } from "../writer";

function streamToBuffer(doc: PDFKit.PDFDocument) {
  return new Promise<Buffer>((resolve, reject) => {
    const chunks: Buffer[] = [];
    doc.on("data", (c) => chunks.push(Buffer.from(c)));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
  });
}

export async function buildPdf(project: Project) {
  const doc = new PDFDocument({
    size: "A4",
    bufferPages: true,
    margins: { top: 72, bottom: 72, left: 72, right: 72 },
    info: {
      Title: project.topic,
      Author: project.authorName || "Quill",
      Subject: `${project.documentType} generated by Quill`,
    },
  });
  const done = streamToBuffer(doc);
  const meta = frontMatter(project);
  const pageWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;

  const footer = () => {
    const range = doc.bufferedPageRange();
    const page = range.start + range.count;
    doc.fontSize(9).fillColor("#64748b").text(
      `Quill  ·  ${project.topic.slice(0, 48)}  ·  ${page}`,
      doc.page.margins.left,
      doc.page.height - 48,
      { width: pageWidth, align: "center" }
    );
    doc.fillColor("#0f172a");
  };

  doc.on("pageAdded", footer);

  doc.rect(0, 0, doc.page.width, doc.page.height).fill("#0b1220");
  doc.fillColor("#e2e8f0");
  doc.font("Times-Bold").fontSize(11).text("QUILL RESEARCH STUDIO", 72, 120, { align: "left" });
  doc.moveDown(2);
  doc.fontSize(28).text(meta.title, { width: pageWidth, align: "left" });
  doc.moveDown(0.8);
  doc.font("Times-Italic").fontSize(14).fillColor("#94a3b8").text(meta.subtitle, { width: pageWidth });
  doc.moveDown(2);
  doc.font("Times-Roman").fontSize(13).fillColor("#e2e8f0").text(meta.author);
  doc.text(meta.institution);
  doc.text(String(meta.year));
  doc.addPage();

  doc.fillColor("#0f172a");
  heading(doc, "Abstract");
  doc.font("Times-Roman").fontSize(11).text(meta.abstract, { align: "justify", lineGap: 3 });
  doc.moveDown();
  doc.font("Times-Bold").fontSize(11).text("Keywords");
  doc.font("Times-Roman").text(meta.keywords.join(" · "));
  doc.addPage();

  heading(doc, "Table of contents");
  project.chapters.forEach((ch) => {
    doc.font("Times-Roman").fontSize(12).text(`Chapter ${ch.number}.  ${ch.title}`, { lineGap: 6 });
  });
  doc.moveDown();
  doc.text("References");
  doc.addPage();

  project.chapters.forEach((ch, idx) => {
    writeChapter(doc, ch);
    if (idx !== project.chapters.length - 1) doc.addPage();
  });

  doc.addPage();
  heading(doc, "References");
  project.bibliography.forEach((entry) => {
    doc.font("Times-Roman").fontSize(10.5).text(entry, { indent: 18, lineGap: 4, paragraphGap: 6, align: "left" });
  });

  footer();
  doc.end();
  return done;
}

function heading(doc: PDFKit.PDFDocument, text: string) {
  doc.font("Times-Bold").fontSize(16).fillColor("#0f172a").text(text, { paragraphGap: 10 });
}

function writeChapter(doc: PDFKit.PDFDocument, chapter: Chapter) {
  chapter.blocks.forEach((block) => {
    const size = block.level === 1 ? 16 : block.level === 2 ? 13 : 11.5;
    doc.moveDown(block.level === 1 ? 0.2 : 0.6);
    doc.font("Times-Bold").fontSize(size).fillColor("#0f172a").text(block.heading, { paragraphGap: 8 });
    doc.font("Times-Roman").fontSize(11).fillColor("#1e293b");
    block.paragraphs.forEach((p) => {
      doc.text(p, { align: "justify", lineGap: 3, paragraphGap: 8 });
    });
  });
}
